export const challengeLanguages = ['All', 'Python', 'JavaScript', 'HTML', 'Java', 'C#'];

export function getPack(id: string): ChallengePack | undefined {
  return challengePacks.find((item) => item.id === id);
}

export function packXp(item: ChallengePack): number {
  return item.challenges.reduce((sum, challenge) => sum + challenge.xp, 0);
}
