function pack(
  id: string,
  language: string,
  topic: string,
  emoji: string,
  color: string,
  description: string,
  filename: string,
  challenges: Challenge[],
  club = false,
): ChallengePack {
  return { id, language, topic, emoji, color, description, duration: '30 min', club, filename, challenges };
}

function simple(
  slug: string,
  title: string,
  emoji: string,
  difficulty: Difficulty,
  prompt: string[],
  input: string,
  output: string,
  example: string,
  hint: string,
  tips: string[],
  starter: string,
): Challenge {
  return { slug, title, emoji, difficulty, xp: 5, prompt, input, output, example, hint, tips, starter };
}

