/**
 * Challenge Packs — five short problems per pack, worth 30 XP together.
 * Copy is bilingual by design: the problem statements are the place students
 * most need Mongolian, so both languages ship in the data.
 */

export type Difficulty = 'EASY' | 'MEDIUM' | 'HARD';

export type Challenge = {
  slug: string;
  title: string;
  emoji: string;
  difficulty: Difficulty;
  xp: number;
  /** Problem statement, one paragraph per entry. */
  prompt: string[];
  input: string;
  output: string;
  example: string;
  hint: string;
  tips: string[];
  starter: string;
};

export type ChallengePack = {
  id: string;
  language: string;
  topic: string;
  emoji: string;
  /** Radial burst colour behind the pixel icon. */
  color: string;
  description: string;
  duration: string;
  club?: boolean;
  filename: string;
  challenges: Challenge[];
};

